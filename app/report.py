from app.tarot import draw_reflection_card

def build_report(date_text: str, number: int, numerology_text: str) -> str:
    card = draw_reflection_card()
    return (
        "✨ ТВОЙ ДЕМОНСТРАЦИОННЫЙ ОТЧЁТ\n\n"
        f"Дата для расчёта: {date_text}\n\n"
        f"1. ЧИСЛОВАЯ ТЕМА\nЧисло жизненного пути: {number}\n{numerology_text}\n\n"
        f"2. АРХЕТИП ДЛЯ РАЗМЫШЛЕНИЯ\n{card['name']} — {card['theme']}.\n"
        f"Вопрос: {card['question']}\n\n"
        "3. КАК ОБЪЕДИНЯТЬ РЕЗУЛЬТАТЫ\n"
        "Не воспринимай совпадения как доказательство судьбы. Отметь, какие темы откликаются, "
        "какие не подходят, и сравни их с реальными обстоятельствами.\n\n"
        "4. ПРАКТИЧЕСКИЙ ШАГ\n"
        "Запиши один вывод, который кажется полезным, и одно конкретное действие на ближайшую неделю.\n\n"
        "ОГРАНИЧЕНИЕ\n"
        "Это символический отчёт для саморефлексии. Астрологическая карта здесь не рассчитана, "
        "а результаты не являются научной оценкой личности или предсказанием будущего."
    )
